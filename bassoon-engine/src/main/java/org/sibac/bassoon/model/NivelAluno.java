package org.sibac.bassoon.model;

/**
 * Nivel global do aluno.
 * Cada nivel corresponde a uma faixa de dificuldade de obras (regra R1):
 *   INICIANTE   -> obras de dificuldade 1-2
 *   INTERMEDIO  -> obras de dificuldade 3-4
 *   AVANCADO    -> obras de dificuldade 5-6
 */
public enum NivelAluno {
    INICIANTE,
    INTERMEDIO,
    AVANCADO
}
